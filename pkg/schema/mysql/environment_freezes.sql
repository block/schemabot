CREATE TABLE `environment_freezes` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `freeze_identifier` varchar(255) NOT NULL,
  `environment` varchar(255) NOT NULL,
  `scope_deployments` json NOT NULL,
  `scope_databases` json NOT NULL,
  `kind` varchar(32) NOT NULL,
  `running_policy` varchar(32) NOT NULL,
  `starts_at` datetime(6) NOT NULL,
  `ends_at` datetime(6) DEFAULT NULL,
  `reason` text NOT NULL,
  `created_by` varchar(255) NOT NULL,
  `source` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  `external_id` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `lifted_by` varchar(255) DEFAULT NULL,
  `lift_reason` text,
  `lifted_at` datetime(6) DEFAULT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `idx_freeze_identifier` (`freeze_identifier`),
  UNIQUE KEY `idx_source_external_id` (`source`,`external_id`),
  KEY `idx_environment_starts_at` (`environment`,`starts_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
