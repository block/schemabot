CREATE TABLE operator_servers (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  server_id varchar(255) NOT NULL,
  drivers integer NOT NULL,
  deferred_cutover_drivers integer NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX idx_operator_servers_server_id ON operator_servers (server_id);
CREATE INDEX idx_operator_servers_updated_at ON operator_servers (updated_at);
