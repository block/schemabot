CREATE TABLE environment_freezes (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  freeze_identifier varchar(255) NOT NULL,
  environment varchar(255) NOT NULL,
  scope_deployments jsonb NOT NULL,
  scope_databases jsonb NOT NULL,
  kind varchar(32) NOT NULL,
  override_rule varchar(32) NOT NULL,
  starts_at timestamp NOT NULL,
  ends_at timestamp DEFAULT NULL,
  reason text NOT NULL,
  created_by varchar(255) NOT NULL,
  source varchar(64) NOT NULL,
  external_id varchar(255) DEFAULT NULL,
  lifted_by varchar(255) DEFAULT NULL,
  lift_reason text DEFAULT NULL,
  lifted_at timestamp DEFAULT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX idx_environment_freezes_freeze_identifier ON environment_freezes (freeze_identifier);
CREATE UNIQUE INDEX idx_environment_freezes_source_external_id ON environment_freezes (source, external_id);
CREATE INDEX idx_environment_freezes_environment_starts_at ON environment_freezes (environment, starts_at);
