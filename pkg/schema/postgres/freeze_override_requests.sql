CREATE TABLE freeze_override_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  override_identifier varchar(255) NOT NULL,
  environment varchar(255) NOT NULL,
  action varchar(32) NOT NULL,
  target_id varchar(255) NOT NULL,
  database_name varchar(255) NOT NULL,
  repository varchar(255) NOT NULL,
  pull_request integer NOT NULL,
  pr_author varchar(255) DEFAULT NULL,
  blockers jsonb NOT NULL,
  reason text NOT NULL,
  requested_by varchar(255) NOT NULL,
  approved_by varchar(255) DEFAULT NULL,
  approved_at timestamp DEFAULT NULL,
  expires_at timestamp NOT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX idx_freeze_override_requests_override_identifier ON freeze_override_requests (override_identifier);
CREATE INDEX idx_freeze_override_requests_environment_action_target ON freeze_override_requests (environment, action, target_id);
