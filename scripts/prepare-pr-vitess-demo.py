#!/usr/bin/env python3
"""Prepare GitHub-rendered comment bodies for the Vitess PR workflow recording.
pkg/cmd/prdemo/vitess.go renders the comments through the production templates
with fictional values; render-pr-demo.cjs vitess uses the committed output offline.
Requires authenticated gh and Go.
"""
from pathlib import Path
import json,re,runpy,subprocess
root=Path(__file__).resolve().parent.parent
m=runpy.run_path(str(root/'scripts/render-pr-mockups.py'))
cache={}
try:
 out=subprocess.run(['go','run','./pkg/cmd/prdemo/vitess.go'],cwd=root,check=True,capture_output=True,text=True).stdout
except subprocess.CalledProcessError as e:
 m['fail'](f"go run ./pkg/cmd/prdemo/vitess.go failed: {e.stderr.strip()}")
raw=json.loads(out)
render=lambda body:m['render_markdown'](m['prepare'](body),cache)
comments={name:render(raw[name]) for name in ('plan','apply','cutover','revert','complete','summary')}
# One rendered progress comment per polling update, keyed by percent.
comments['running']={p:render(body) for p,body in raw['running'].items()}
assert '100' in comments['running'] and '0' in comments['running']
# Use GitHub's SQL highlighter for the opening file diff, too. The pull request
# adds the note column to a table sharded on customer_id.
schema="""CREATE TABLE `orders` (
  `id` bigint unsigned NOT NULL,
  `customer_id` bigint unsigned NOT NULL,
  `note` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;"""
highlighted=m['render_markdown']('```sql\n'+schema+'\n```',cache)
comments['diffLines']=re.search(r'<pre\b[^>]*>(.*?)</pre>',highlighted,re.S).group(1).splitlines()
assert len(comments['diffLines'])==6
(root/'assets/src/pr-vitess-comments.js').write_text('// Generated by scripts/prepare-pr-vitess-demo.py from pkg/cmd/prdemo/vitess.go\nwindow.COMMENTS = '+json.dumps(comments,ensure_ascii=False)+';\n')
print('Prepared the GitHub-rendered Vitess comment bodies')
