#!/usr/bin/env python3
"""Build the SchemaBot documentation website from README.md and docs/.

Run via `make docs-site` (see Makefile), which installs the pinned
requirements into a virtualenv first. The docs stay ordinary Markdown that
reads well on GitHub; this script stages a copy that MkDocs can render:

  README.md                       -> index.md (the home page)
  docs/<name>.md                  -> <name>.md
  assets a page links to          -> assets/

Links are rewritten on the way: a link to another doc or to an asset points
at its staged copy, and a link to anything else in the repository (source
files, examples, CONTRIBUTING.md) points at that file on GitHub. A relative
link to a file that does not exist fails the build, so a broken link cannot
reach the site. MkDocs rewrites Markdown links to the rendered pages but
leaves raw HTML alone, so links in HTML src and href attributes point at the
rendered URL directly.

After MkDocs renders the HTML, the script adds the files AI tools read
(https://llmstxt.org): llms.txt, an index of every page with a one-line
description, llms-full.txt, every page in one file, and a Markdown copy of
each page next to its HTML. Links in those point at the published site.

Navigation order comes from the `nav` in mkdocs.yml. Every doc under docs/
must appear there exactly once, so a new doc cannot be left off the site.
"""

from __future__ import annotations

import argparse
import itertools
import os
import posixpath
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_PATH = REPO_ROOT / "mkdocs.yml"
GITHUB_BLOB = "https://github.com/block/schemabot/blob/main/"
GITHUB_TREE = "https://github.com/block/schemabot/tree/main/"
HOME_PAGE = "index.md"

TOC_BLOCK = re.compile(
    r"<!-- BEGIN TOC \(auto-generated by `make docs-toc`[^>]*-->.*?"
    r"<!-- END TOC \(auto-generated by `make docs-toc`\) -->\n*",
    re.DOTALL,
)
FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})")
# Markdown link and image targets, and HTML src/href attributes.
MD_LINK = re.compile(r"(\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")
HTML_ATTR = re.compile(r"""((?:src|href)=")([^"]+)(")""")
LIST_ITEM = re.compile(r"^ *(?:[-*+]|\d+[.)]) ")
DETAILS_OPEN = re.compile(r"<details(?![^>]*\bmarkdown=)([^>]*)>")


class BuildError(Exception):
    """A problem in the docs that must be fixed before the site can build."""


def staging_dir(docs_dir: str, repo_root: Path) -> Path:
    """Return the directory the pages are staged in, which the build deletes and
    recreates. It must sit strictly inside the repository's build/ tree, so an
    edit to docs_dir can never point the delete at source files."""
    build_root = (repo_root / "build").resolve()
    staged = (repo_root / docs_dir).resolve()
    if not staged.is_relative_to(build_root) or staged == build_root:
        raise BuildError(f"mkdocs.yml docs_dir must be a directory inside build/, not {docs_dir!r}: the build deletes it")
    return staged


@dataclass(frozen=True)
class Page:
    """One page of the site, in navigation order."""

    section: str
    staged: str  # file name in the staged docs dir, e.g. "cli.md"
    source: str  # repo-relative source path, e.g. "docs/cli.md"


def staged_name(source: str) -> str:
    """Return the staged file name for a repo-relative source path."""
    if source == "README.md":
        return HOME_PAGE
    return posixpath.basename(source)


def source_path(staged: str) -> str:
    """Return the repo-relative source path for a staged file name."""
    if staged == HOME_PAGE:
        return "README.md"
    return f"docs/{staged}"


def load_config(path: Path) -> dict:
    """Load mkdocs.yml, ignoring the python/ tags that only MkDocs resolves."""
    import yaml  # installed with mkdocs; imported here so tests need not have it

    class Loader(yaml.SafeLoader):
        pass

    Loader.add_multi_constructor(
        "tag:yaml.org,2002:python/", lambda loader, suffix, node: None
    )
    return yaml.load(path.read_text(), Loader=Loader)


def pages_from_nav(nav: list) -> list[Page]:
    """Flatten mkdocs.yml nav into pages, keeping the top-level section name."""
    pages: list[Page] = []
    for entry in nav:
        if not isinstance(entry, dict) or len(entry) != 1:
            raise BuildError(f"nav entries must be single-key mappings, got {entry!r}")
        (section, value), = entry.items()
        items = [value] if isinstance(value, str) else value
        if not isinstance(items, list):
            raise BuildError(f"nav section {section!r} must be a file or a list of files, got {value!r}")
        for item in items:
            name = nav_file(section, item)
            pages.append(Page(section=section, staged=name, source=source_path(name)))
    return pages


def nav_file(section: str, item) -> str:
    """Return the file a nav item names: "cli.md" or {"Title": "cli.md"}."""
    if isinstance(item, str):
        return item
    if isinstance(item, dict) and len(item) == 1 and isinstance(next(iter(item.values())), str):
        return next(iter(item.values()))
    raise BuildError(
        f"nav section {section!r} has an entry that is not a file: {item!r}; "
        "nested sections are not supported"
    )


def check_descriptions(pages: list[Page], descriptions: dict) -> None:
    """Fail unless every page has a description and every description a page."""
    names = {p.staged for p in pages}
    missing = sorted(n for n in names if not str(descriptions.get(n) or "").strip())
    if missing:
        raise BuildError(f"missing from extra.descriptions in mkdocs.yml: {', '.join(missing)}")
    unknown = sorted(set(descriptions) - names)
    if unknown:
        raise BuildError(f"extra.descriptions names pages that are not in nav: {', '.join(unknown)}")


def check_nav_complete(pages: list[Page], doc_names: list[str]) -> None:
    """Fail unless every doc is in the nav exactly once and nothing else is."""
    staged = [p.staged for p in pages]
    duplicates = sorted({n for n in staged if staged.count(n) > 1})
    if duplicates:
        raise BuildError(f"listed more than once in mkdocs.yml nav: {', '.join(duplicates)}")
    expected = set(doc_names) | {HOME_PAGE}
    missing = sorted(expected - set(staged))
    if missing:
        raise BuildError(
            "missing from mkdocs.yml nav, so the site would not link them: "
            + ", ".join(f"docs/{n}" for n in missing)
        )
    unknown = sorted(set(staged) - expected)
    if unknown:
        raise BuildError(f"mkdocs.yml nav names files that do not exist: {', '.join(unknown)}")


def is_external(target: str) -> bool:
    return bool(re.match(r"^[a-z][a-z0-9+.-]*:", target, re.IGNORECASE)) or target.startswith("//")


def is_site_page(path: str) -> bool:
    """Whether a repo-relative path is one of the pages the site renders."""
    if path == "README.md":
        return True
    return path.startswith("docs/") and path.endswith(".md") and "/" not in path[len("docs/"):]


def resolve_target(target: str, source: str, repo_root: Path, links, html: bool = False) -> str:
    """Rewrite one link target found in `source` (a repo-relative path).

    `links` builds the link to another page or to an asset, so the same
    resolution serves both the staged site (relative links) and the Markdown
    copies for AI tools (absolute links). `html` marks a target taken from an
    HTML attribute, which MkDocs does not rewrite.
    """
    if not target or target.startswith("#") or is_external(target):
        return target
    path, _, anchor = target.partition("#")
    resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
    if resolved.startswith("../") or resolved == "..":
        raise BuildError(f"{source}: link {target!r} points outside the repository")
    on_disk = repo_root / resolved
    if not on_disk.exists():
        raise BuildError(f"{source}: link {target!r} points at {resolved}, which does not exist")
    suffix = f"#{anchor}" if anchor else ""
    if is_site_page(resolved):
        return links.page(staged_name(resolved), anchor, source, html)
    if resolved.startswith("assets/"):
        return links.asset(resolved, source, html) + suffix
    base = GITHUB_TREE if on_disk.is_dir() else GITHUB_BLOB
    return f"{base}{resolved}{suffix}"


class SiteLinks:
    """Links between staged files, as the staged pages need them.

    A Markdown link names the staged file, and MkDocs turns it into the
    rendered page's URL. An HTML attribute gets the rendered URL itself,
    relative to where the linking page renders: the home page at the site
    root, every other page one directory down (use_directory_urls).

    Records each asset a page links to, so only those are published.
    """

    def __init__(self) -> None:
        self.assets: set[str] = set()

    def page(self, name: str, anchor: str | None, source: str, html: bool) -> str:
        fragment = f"#{anchor}" if anchor else ""
        if not html:
            return name + fragment
        rendered = "" if name == HOME_PAGE else name[: -len(".md")] + "/"
        return (rendered_prefix(source) + rendered or "./") + fragment

    def asset(self, path: str, source: str, html: bool) -> str:
        self.assets.add(path)
        return rendered_prefix(source) + path if html else path


def rendered_prefix(source: str) -> str:
    """Return the path from where `source` renders back to the site root."""
    return "" if staged_name(source) == HOME_PAGE else "../"


class PublishedLinks:
    """Absolute links to the published HTML pages and assets."""

    def __init__(self, site_url: str):
        self.site_url = site_url.rstrip("/") + "/"

    def page(self, name: str, anchor: str | None, source: str = "", html: bool = False) -> str:
        stem = name[: -len(".md")]
        page = "" if name == HOME_PAGE else f"{stem}/"
        return self.site_url + page + (f"#{anchor}" if anchor else "")

    def asset(self, path: str, source: str = "", html: bool = False) -> str:
        return self.site_url + path


def rewrite_links(text: str, source: str, repo_root: Path, links) -> str:
    """Rewrite link targets outside fenced code blocks."""

    def rewrite_line(line: str) -> str:
        line = MD_LINK.sub(
            lambda m: m.group(1) + resolve_target(m.group(2), source, repo_root, links) + m.group(3),
            line,
        )
        return HTML_ATTR.sub(
            lambda m: m.group(1) + resolve_target(m.group(2), source, repo_root, links, html=True) + m.group(3),
            line,
        )

    return "".join(line if fenced else rewrite_line(line) for line, fenced in lines_with_fences(text))


def lines_with_fences(text: str):
    """Yield each line with whether it belongs to a fenced code block."""
    fence: str | None = None
    for line in text.splitlines(keepends=True):
        match = FENCE.match(line)
        if fence is None and match:
            fence = match.group(2)
            yield line, True
        elif fence is not None:
            if match and match.group(2).startswith(fence[0] * len(fence)) and line.strip() == match.group(2):
                fence = None
            yield line, True
        else:
            yield line, False


def check_list_indentation(text: str, source: str) -> None:
    """Fail on list content indented less than four spaces.

    GitHub accepts content under a list item at the item's text column, so a
    paragraph, image, code block, or nested list indented two or three spaces
    stays in the list there. Python-Markdown needs four, so on the site that
    content drops out of the list: a nested list renders flat, and the
    numbering restarts at 1 after it. Four spaces renders the same on both.
    """
    previous_blank = False
    for number, (line, fenced) in enumerate(lines_with_fences(text), start=1):
        indent = len(line) - len(line.lstrip(" "))
        # A fence opening line counts; its contents do not.
        opens_fence = fenced and FENCE.match(line) is not None
        checked = not fenced or opens_fence
        nested_item = LIST_ITEM.match(line) is not None
        if checked and 0 < indent < 4 and line.strip() and (nested_item or previous_blank):
            raise BuildError(
                f"{source}:{number}: indent list content by four spaces; "
                f"with {indent} the site drops it out of the list"
            )
        previous_blank = not line.strip()


def strip_toc(text: str) -> str:
    """Drop the in-page TOC block; the site renders its own TOC beside the page."""
    return TOC_BLOCK.sub("", text)


def front_matter(title: str | None, description: str) -> str:
    lines = ["---"]
    if title:
        lines.append(f"title: {quote_yaml(title)}")
    if description:
        lines.append(f"description: {quote_yaml(description)}")
    lines.append("---\n\n")
    return "\n".join(lines)


def quote_yaml(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def page_title(text: str, fallback: str) -> str:
    match = re.search(r"^# (.+)$", text, re.MULTILINE)
    return match.group(1).strip() if match else fallback


def stage_site_page(text: str, page: Page, description: str, repo_root: Path, links: SiteLinks) -> str:
    """Return the Markdown MkDocs renders for one page."""
    text = strip_toc(text)
    check_list_indentation(text, page.source)
    body = rewrite_links(text, page.source, repo_root, links)
    # Python-Markdown leaves HTML blocks alone unless asked; GitHub renders
    # Markdown inside <details>, so ask for the same here.
    body = DETAILS_OPEN.sub(r'<details markdown="1"\1>', body)
    title = "SchemaBot" if page.staged == HOME_PAGE else None
    return front_matter(title, description) + body


def published_markdown(text: str, page: Page, repo_root: Path, site_url: str) -> str:
    """Return the Markdown copy published for AI tools, with absolute links."""
    return rewrite_links(strip_toc(text), page.source, repo_root, PublishedLinks(site_url)).strip() + "\n"


def markdown_url(site_url: str, page: Page) -> str:
    return site_url.rstrip("/") + "/" + page.staged


def build_llms_txt(config: dict, pages: list[Page], descriptions: dict[str, str], titles: dict[str, str]) -> str:
    site_url = config["site_url"]
    lines = [
        f"# {config['site_name']}",
        "",
        f"> {config['site_description']}",
        "",
        "Each link below is the Markdown source of one documentation page. The HTML version of a page lives at the same path without the .md suffix. llms-full.txt has every page in one file.",
        "",
    ]
    for section, section_pages in itertools.groupby(pages, key=lambda p: p.section):
        lines += [f"## {section}", ""]
        for page in section_pages:
            lines.append(f"- [{titles[page.staged]}]({markdown_url(site_url, page)}): {descriptions[page.staged]}")
        lines.append("")
    return "\n".join(lines)


def build_llms_full(config: dict, pages: list[Page], published: dict[str, str]) -> str:
    parts = [f"# {config['site_name']}\n\n> {config['site_description']}\n"]
    for page in pages:
        url = PublishedLinks(config["site_url"]).page(page.staged, None)
        parts.append(f"<!-- Source: {url} -->\n\n{published[page.staged]}")
    return "\n\n".join(parts)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", help="directory the site is written to (default: site_dir in mkdocs.yml)")
    parser.add_argument("--mkdocs", default="mkdocs", help="the mkdocs executable to run")
    args = parser.parse_args(argv)

    try:
        config = load_config(CONFIG_PATH)
        # MkDocs reads the pages from docs_dir, so they are always staged there.
        staged_dir = staging_dir(config["docs_dir"], REPO_ROOT)
        html_dir = Path(args.out) if args.out else REPO_ROOT / config["site_dir"]
        if config.get("use_directory_urls", True) is not True:
            raise BuildError("mkdocs.yml must keep use_directory_urls on; HTML links assume page/ URLs")
        pages = pages_from_nav(config["nav"])
        doc_names = sorted(p.name for p in (REPO_ROOT / "docs").glob("*.md"))
        check_nav_complete(pages, doc_names)
        descriptions = {k: " ".join(str(v).split()) for k, v in (config.get("extra", {}).get("descriptions") or {}).items()}
        check_descriptions(pages, descriptions)
        sources = {p.staged: (REPO_ROOT / p.source).read_text() for p in pages}
        site_links = SiteLinks()
        staged = {p.staged: stage_site_page(sources[p.staged], p, descriptions[p.staged], REPO_ROOT, site_links) for p in pages}
        published = {
            p.staged: published_markdown(sources[p.staged], p, REPO_ROOT, config["site_url"])
            for p in pages
        }
    except BuildError as err:
        print(f"docs-site: {err}", file=sys.stderr)
        return 1

    shutil.rmtree(staged_dir, ignore_errors=True)
    staged_dir.mkdir(parents=True)
    for name, text in staged.items():
        (staged_dir / name).write_text(text)
    # The theme's logo and favicon, plus every asset a page links to.
    for asset in sorted(site_links.assets | {config["theme"]["logo"], config["theme"]["favicon"]}):
        (staged_dir / asset).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(REPO_ROOT / asset, staged_dir / asset)

    result = subprocess.run(
        [args.mkdocs, "build", "--strict", "--config-file", str(CONFIG_PATH), "--site-dir", str(html_dir)],
        cwd=REPO_ROOT,
        # Material prints a notice about MkDocs 2.0 on every build.
        # requirements.txt pins MkDocs 1.x, so the notice does not apply.
        env={**os.environ, "NO_MKDOCS_2_WARNING": "1"},
        check=False,
    )
    if result.returncode != 0:
        print("docs-site: mkdocs build failed", file=sys.stderr)
        return result.returncode

    titles = {p.staged: ("SchemaBot" if p.staged == HOME_PAGE else page_title(sources[p.staged], p.staged)) for p in pages}
    for name, text in published.items():
        (html_dir / name).write_text(text)
    (html_dir / "llms.txt").write_text(build_llms_txt(config, pages, descriptions, titles))
    (html_dir / "llms-full.txt").write_text(build_llms_full(config, pages, published))
    print(f"docs-site: wrote {len(pages)} pages to {html_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
