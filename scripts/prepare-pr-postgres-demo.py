#!/usr/bin/env python3
"""Prepare GitHub-rendered comment bodies for the PostgreSQL PR workflow recording.
pkg/cmd/prdemo/postgres.go renders the comments through the production templates
with fictional values; render-pr-demo.cjs postgres uses the committed output offline.
Requires authenticated gh and Go.
"""
from pathlib import Path
import json,re,runpy,subprocess
root=Path(__file__).resolve().parent.parent
m=runpy.run_path(str(root/'scripts/render-pr-mockups.py'))
cache={}
raw=json.loads(subprocess.run(['go','run','./pkg/cmd/prdemo/postgres.go'],cwd=root,check=True,capture_output=True,text=True).stdout)
render=lambda body:m['render_markdown'](m['prepare'](body),cache)
comments={name:render(raw[name]) for name in ('plan','apply','complete','summary')}
# One rendered progress comment per polling update, keyed by percent.
comments['running']={p:render(body) for p,body in raw['running'].items()}
assert '100' in comments['running'] and '0' in comments['running']
# Use GitHub's SQL highlighter for the opening file diff, too.
schema='''CREATE TABLE "users" (
    "id" bigint NOT NULL,
    "email" text,
    "created_at" timestamptz NOT NULL,
    CONSTRAINT "users_pkey" PRIMARY KEY (id)
);

CREATE INDEX "idx_email_created" ON "users" (email, created_at);'''
highlighted=m['render_markdown']('```sql\n'+schema+'\n```',cache)
comments['diffLines']=re.search(r'<pre\b[^>]*>(.*?)</pre>',highlighted,re.S).group(1).splitlines()
assert len(comments['diffLines'])==8
(root/'assets/src/pr-postgres-comments.js').write_text('// Generated by scripts/prepare-pr-postgres-demo.py from pkg/cmd/prdemo/postgres.go\nwindow.COMMENTS = '+json.dumps(comments,ensure_ascii=False)+';\n')
print('Prepared the GitHub-rendered PostgreSQL comment bodies')
